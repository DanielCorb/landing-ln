/**
 * A *post* is the single content entity of Lumea Nouă.
 *
 * Terminology — this is deliberate and load-bearing:
 *   - **postare / post**  → the thing that is written, edited, scheduled and published.
 *   - **rubrică**         → the section a post is filed under. There are exactly three:
 *                           `articole`, `traduceri`, `contributiile-cititorilor`.
 *
 * "Articole" is therefore *one rubrică out of three*, never a synonym for "post".
 * Anything that applies to a post applies to all three rubrici.
 *
 * The Firestore collection is still physically named `articles` (see
 * `POSTS_COLLECTION`) because renaming it would require migrating live data.
 */

export type PostStatus = 'draft' | 'published' | 'scheduled' | 'archived';

/** Slug of one of the three fixed rubrici a post can be filed under. */
export type Rubrica = 'articole' | 'traduceri' | 'contributiile-cititorilor';

export interface Post {
  /** Firestore document ID */
  id: string;
  /** Post title */
  title: string;
  /** URL-friendly slug (generated by the dashboard's getSlug util) */
  slug: string;
  /** Introductory/lead text shown prominently before the body */
  lead: string;
  /** Full post content as HTML produced by the dashboard's rich text editor */
  body: string;
  /** Firebase Storage URL for the cover image, or null */
  coverImageUrl: string | null;
  /** Which rubrică this post is filed under */
  rubrica: Rubrica;
  /** Publication status — the public site only ever shows published posts */
  status: PostStatus;
  /** Publish date — null while the post is still a draft */
  publishAt: Date | null;
  /** When the post was first created */
  createdAt: Date;
  /** When the post was last modified */
  updatedAt: Date;
  /** UID of the author (from dashboard auth) */
  authorId: string;
  /**
   * Byline for a reader's contribution — the person who wrote the piece.
   *
   * Distinct from `authorId`, which identifies the dashboard account that filed the post.
   * Only set on posts in the `contributiile-cititorilor` rubrică; `null` everywhere else.
   */
  contributor: string | null;
}

/** Sort direction accepted by the post listing queries. */
export type PostSort = 'newest' | 'oldest';

/** Layout used to render a list of posts. */
export type PostListView = 'grid' | 'list';

/** Options accepted by the paginated published-post query. */
export interface PublishedPostsQuery {
  page?: number;
  pageSize?: number;
  rubrica?: Rubrica;
  /** Inclusive lower bound, `yyyy-MM-dd` */
  dateStart?: string;
  /** Inclusive upper bound, `yyyy-MM-dd` */
  dateEnd?: string;
  sort?: PostSort;
  /** Exact contributor name; only meaningful for the contributions rubrică. */
  author?: string;
}

/** Result of a paginated published-post query. */
export interface PublishedPostsResult {
  posts: Post[];
  total: number;
}
